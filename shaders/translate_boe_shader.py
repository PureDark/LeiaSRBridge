"""Reproducibly translate the vendor's independent interlace CS to a PS.

No vendor DLL is loaded. Exact DXBC literals come from D3DDisassemble's
PRINT_HEX_LITERALS mode, not its rounded human-readable decimal output.
The generated HLSL implements the register operations mechanically. The only
stage changes are SV_DispatchThreadID -> viewport-local SV_Position and the
single UAV store -> SV_Target. This script rejects every unsupported opcode.
"""
import ctypes
import hashlib
import re
import struct
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DLL = ROOT / 'RE/inputs/depth/interlaceSDK.dll'
EXPECTED = '380a9194a5c2ab42cf1f70a2b3c383f9b340b3b292ac72177350aa0dae56cc6f'
image = DLL.read_bytes()
assert hashlib.sha256(image).hexdigest() == EXPECTED
# VA decimal verified by IDA int_convert in interlace_conversions.json.
va, size = 6443014208, 23656
pe = struct.unpack_from('<I', image, 60)[0]
count, opt_size = struct.unpack_from('<H', image, pe+6)[0], struct.unpack_from('<H', image, pe+20)[0]
base = struct.unpack_from('<Q', image, pe+48)[0]
for i in range(count):
    section = pe+24+opt_size+i*40
    vsize, rva, rsize, raw = struct.unpack_from('<IIII', image, section+8)
    if rva <= va-base < rva+max(vsize,rsize):
        start = raw+va-base-rva
        shader = image[start:start+size]
        break
else:
    raise RuntimeError('Shader not found')
assert shader[:4] == b'DXBC' and struct.unpack_from('<I', shader,24)[0] == size
(HERE/'BoeOriginalCS.dxbc').write_bytes(shader)
compiler=ctypes.WinDLL('d3dcompiler_47.dll')
compiler.D3DDisassemble.argtypes=[ctypes.c_void_p,ctypes.c_size_t,ctypes.c_uint,ctypes.c_char_p,ctypes.POINTER(ctypes.c_void_p)]
compiler.D3DDisassemble.restype=ctypes.c_long
blob=ctypes.c_void_p()
assert compiler.D3DDisassemble(shader,len(shader),128,None,ctypes.byref(blob)) >= 0
vt=ctypes.cast(blob,ctypes.POINTER(ctypes.POINTER(ctypes.c_void_p)))[0]
ptr=ctypes.WINFUNCTYPE(ctypes.c_void_p,ctypes.c_void_p)(vt[3])(blob)
length=ctypes.WINFUNCTYPE(ctypes.c_size_t,ctypes.c_void_p)(vt[4])(blob)
assembly=ctypes.string_at(ptr,length).rstrip(b'\0').decode()
ctypes.WINFUNCTYPE(ctypes.c_ulong,ctypes.c_void_p)(vt[2])(blob)
(HERE/'BoeOriginalCS.exact.asm').write_text(assembly)

def operands(s):
    return re.split(r',\s*(?![^()]*\))',s)

def value(s, integer=False):
    s=s.strip()
    if s.startswith('-'):
        cast='asint' if integer else 'asfloat'
        return f'asuint(-{cast}({value(s[1:],integer)}))'
    if s.startswith('|'):
        return f'asuint(abs(asfloat({value(s[1:-1])})))'
    if s.startswith('l('):
        parts=operands(s[2:-1])
        bits=[]
        for p in parts:
            if p.startswith('0x'): bits.append(p+'u')
            elif '.' not in p: bits.append(f'asuint(int({p}))')
            else: raise RuntimeError('Rounded float literal is forbidden: '+p)
        if len(bits)==1: bits*=4
        assert len(bits)==4
        return 'uint4('+','.join(bits)+')'
    match=re.fullmatch(r'(r\d+|cb0\[\d+\]|vThreadID)(?:\.([xyzw]+))?',s)
    assert match,s
    base,swiz=match.groups()
    if base=='vThreadID': base='threadId'
    if base.startswith('cb0'): base=base.replace('cb0','Constants')
    swiz=swiz or 'xyzw'
    if len(swiz)==1: swiz*=4
    assert len(swiz)==4,(s,swiz)
    return base+'.'+swiz

out=['// Generated by translate_boe_shader.py; preserve this provenance.',
     '// Vendor DLL SHA256: '+EXPECTED,
     'Texture2D<float4> InputTexture : register(t0);',
     'cbuffer OpticalConstants : register(b0) { uint4 Constants[5]; };',
     '#include "ColorConversion.hlsli"',
     'float4 main(float4 position : SV_Position) : SV_Target {',
     'uint4 threadId=uint4(uint2(max(position.xy-ViewportOrigin,0.0)),0,0);']
out += [f'precise uint4 r{i}=0;' for i in range(12)]
counter=0
def assign(dst,expr):
    if dst=='null': return
    base,mask=dst.split('.')
    out.append(f'{base}.{mask}=({expr}).{mask};')
def f(v): return f'asfloat({v})'
def si(v): return f'asint({v})'
for raw in assembly.splitlines():
    line=raw.strip()
    if not line or line.startswith('//') or line.startswith('dcl_') or line=='cs_5_0': continue
    op,_,args=line.partition(' ')
    args=operands(args.strip()) if args.strip() else []
    out.append('// '+line)
    counter+=1
    if op=='if_nz': out.append(f'if (({value(args[0])}).x!=0) {{'); continue
    if op=='else': out.append('} else {'); continue
    if op in ('endif','endloop'): out.append('}'); continue
    if op=='loop': out.append('[loop] while (true) {'); continue
    if op=='breakc_nz': out.append(f'if (({value(args[0])}).x!=0) break;'); continue
    if op=='ret': continue
    if op=='store_uav_typed': out.append(f'return ConvertOutput(asfloat({value(args[2])}));'); continue
    if op=='sincos':
        # Both destinations read the original source, including overlapping regs.
        out.append(f'precise float4 sc{counter}={f(value(args[2]))};')
        assign(args[0],f'asuint(sin(sc{counter}))'); assign(args[1],f'asuint(cos(sc{counter}))'); continue
    if op=='imul':
        assert args[0]=='null',line
        assign(args[1],f'({value(args[2],True)}*{value(args[3],True)})');continue
    if op=='udiv':
        assert args[1]=='null',line
        assign(args[0],f'({value(args[2],True)}/{value(args[3],True)})');continue
    if op.startswith('ld_indexable'):
        swiz=args[2].split('.')[1]
        assign(args[0],f'asuint(ReadInput(({si(value(args[1]))}).xyz)).{swiz}');continue
    integer=op in ('and','or','iadd','ushr','imin','imax','ieq','ine','ilt','ige','ult')
    dst=args[0]; src=[value(s,integer) for s in args[1:]]
    if op=='mov': expr=src[0]
    elif op=='movc': expr=f'({src[0]}!=0 ? {src[1]} : {src[2]})'
    elif op in ('add','mul','div'): expr=f'asuint({f(src[0])} '+{'add':'+','mul':'*','div':'/'}[op]+f' {f(src[1])})'
    elif op=='mad': expr=f'asuint(mad({f(src[0])},{f(src[1])},{f(src[2])}))'
    elif op in ('sqrt','frc'): expr=f'asuint({"sqrt" if op=="sqrt" else "frac"}({f(src[0])}))'
    elif op=='utof': expr=f'asuint(float4({src[0]}))'
    elif op in ('lt','ge','ieq','ine','ilt','ige','ult'):
        cast=f if op in ('lt','ge') else si if op in ('ilt','ige') else lambda x:x
        cmp={'lt':'<','ge':'>=','ieq':'==','ine':'!=','ilt':'<','ige':'>=','ult':'<'}[op]
        expr=f'({cast(src[0])} {cmp} {cast(src[1])} ? uint4(0xffffffffu,0xffffffffu,0xffffffffu,0xffffffffu) : uint4(0,0,0,0))'
    elif op in ('and','or','iadd','ushr'): expr=f'({src[0]} '+{'and':'&','or':'|','iadd':'+','ushr':'>>'}[op]+f' {src[1]})'
    elif op in ('imin','imax'): expr=f'asuint({"min" if op=="imin" else "max"}({si(src[0])},{si(src[1])}))'
    else: raise RuntimeError('Unsupported instruction: '+line)
    assign(dst,expr)
out.append('}')
(HERE/'BoeInterlacePS.hlsl').write_text('\n'.join(out)+'\n')
print(f'Translated {counter} exact instructions to BoeInterlacePS.hlsl')
